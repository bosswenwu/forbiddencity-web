const { chromium } = require('playwright');
const fs = require('fs');
const assert = require('assert');
const URL = process.env.E2E_URL || 'http://localhost:8765/index.html';
const shots = 'screenshots';
fs.mkdirSync(shots, { recursive: true });
function collectErrors(page, bucket) {
  page.on('console', msg => { if (msg.type() === 'error') bucket.push('[console] ' + msg.text()); });
  page.on('pageerror', err => bucket.push('[pageerror] ' + err.message));
  page.on('requestfailed', req => bucket.push('[requestfailed] ' + req.url()));
}
(async () => {
  const browser = await chromium.launch({ headless: true });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  collectErrors(page, errors);
  console.log('1/6 load + cover');
  await page.goto(URL, { waitUntil: 'networkidle', timeout: 30000 });
  await page.waitForFunction(() => window.__game?.state().ready);
  await page.screenshot({ path: shots + '/01-cover.png' });
  let state = await page.evaluate(() => window.__game.state());
  assert.equal(state.introVisible, true);
  assert.equal(state.landmarks, 11);
  assert.ok(state.meshes > 500, 'expected a detailed scene');
  console.log('2/6 real keyboard movement');
  await page.locator('#startBtn').click();
  await page.waitForTimeout(250);
  const before = await page.evaluate(() => window.__game.state().position);
  await page.keyboard.down('w');
  await page.waitForTimeout(700);
  await page.keyboard.up('w');
  const after = await page.evaluate(() => window.__game.state().position);
  assert.ok(after[2] < before[2] - 0.5, 'W must move the visitor north');
  await page.screenshot({ path: shots + '/02-walk.png' });
  console.log('3/6 landmark tour');
  await page.evaluate(() => window.__game.teleportToLandmark('太和殿'));
  await page.waitForTimeout(450);
  state = await page.evaluate(() => window.__game.state());
  assert.equal(state.currentLandmark, '太和殿');
  assert.equal(state.mode, 'tour');
  await page.screenshot({ path: shots + '/03-taihe.png' });
  console.log('4/6 aerial overview');
  await page.keyboard.press('Escape');
  await page.evaluate(() => document.exitPointerLock?.());
  await page.waitForFunction(() => !document.pointerLockElement);
  await page.locator('#aerialBtn').click();
  await page.waitForTimeout(450);
  assert.equal(await page.evaluate(() => window.__game.state().mode), 'aerial');
  await page.screenshot({ path: shots + '/04-aerial.png' });
  console.log('5/6 mobile touch controls');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  collectErrors(mobile, errors);
  await mobile.goto(URL, { waitUntil: 'networkidle', timeout: 30000 });
  await mobile.waitForFunction(() => window.__game?.state().ready);
  await mobile.locator('#startBtn').click();
  const mobileBefore = await mobile.evaluate(() => window.__game.state().position);
  const box = await mobile.locator('#joystick').boundingBox();
  await mobile.locator('#joystick').dispatchEvent('pointerdown', { pointerId: 9, pointerType: 'touch', clientX: box.x + box.width / 2, clientY: box.y + box.height / 2 - 32, isPrimary: true });
  await mobile.waitForTimeout(700);
  await mobile.locator('#joystick').dispatchEvent('pointerup', { pointerId: 9, pointerType: 'touch', clientX: box.x + box.width / 2, clientY: box.y + box.height / 2 - 32, isPrimary: true });
  const mobileAfter = await mobile.evaluate(() => window.__game.state().position);
  const mobileState = await mobile.evaluate(() => window.__game.state());
  assert.equal(mobileState.mobile, true);
  assert.ok(mobileAfter[2] < mobileBefore[2] - 0.5, 'touch joystick must move the visitor');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: shots + '/05-mobile.png' });
  console.log('6/6 console + runtime state');
  state = await page.evaluate(() => window.__game.state());
  assert.ok(state.fps > 0);
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('PASS', JSON.stringify({ landmarks: state.landmarks, meshes: state.meshes, fps: state.fps, keyboardDeltaZ: +(after[2] - before[2]).toFixed(2), mobileDeltaZ: +(mobileAfter[2] - mobileBefore[2]).toFixed(2), consoleErrors: 0 }, null, 2));
  await browser.close();
})().catch(err => { console.error('FAIL\n' + (err.stack || err)); process.exit(1); });
